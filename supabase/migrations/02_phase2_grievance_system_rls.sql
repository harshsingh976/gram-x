-- ─── GRIEVANCES RLS ──────────────────────────────────────────
-- Citizens can select their own grievances
create policy "Citizens can view own grievances"
    on public.grievances for select
    using (auth.uid() = citizen_id);

-- Citizens can insert their own grievances
create policy "Citizens can submit grievances"
    on public.grievances for insert
    with check (auth.uid() = citizen_id);

-- Citizens can update status to CLOSED when resolved
create policy "Citizens can close own resolved grievances"
    on public.grievances for update
    using (auth.uid() = citizen_id and status in ('RESOLVED', 'SUBMITTED'));

-- Workers can view grievances assigned to them
create policy "Workers can view assigned grievances"
    on public.grievances for select
    using (auth.uid() = assigned_worker_id);

-- Workers can update status of assigned grievances (IN_PROGRESS, RESOLVED)
create policy "Workers can update assigned grievances"
    on public.grievances for update
    using (auth.uid() = assigned_worker_id);

-- Panchayat Admins and District Collectors have full jurisdictional access
create policy "Admins and District Collectors have full grievance access"
    on public.grievances for all
    using (
        exists (
            select 1 from public.profiles
            where id = auth.uid() and role in ('admin', 'district')
        )
    );

-- ─── GRIEVANCE UPDATES RLS ───────────────────────────────────
create policy "Users can view updates for accessible grievances"
    on public.grievance_updates for select
    using (
        exists (
            select 1 from public.grievances g
            where g.id = grievance_id and (
                g.citizen_id = auth.uid()
                or g.assigned_worker_id = auth.uid()
                or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'district'))
            )
        )
    );

create policy "Authenticated users can insert updates on accessible grievances"
    on public.grievance_updates for insert
    with check (
        auth.uid() is not null and
        exists (
            select 1 from public.grievances g
            where g.id = grievance_id and (
                g.citizen_id = auth.uid()
                or g.assigned_worker_id = auth.uid()
                or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'district'))
            )
        )
    );

-- ─── ASSIGNMENTS & ESCALATIONS RLS ────────────────────────────
create policy "Workers and Admins can view assignments"
    on public.grievance_assignments for select
    using (
        worker_id = auth.uid()
        or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'district'))
    );

create policy "Admins can manage assignments"
    on public.grievance_assignments for all
    using (
        exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'district'))
    );

create policy "Authorized users can view escalations"
    on public.grievance_escalations for select
    using (
        exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'district'))
    );

create policy "Admins and Workers can create escalations"
    on public.grievance_escalations for insert
    with check (
        exists (select 1 from public.profiles p where p.id = auth.uid() and p.role in ('admin', 'district', 'worker'))
    );

